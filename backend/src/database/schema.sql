CREATE TABLE IF NOT EXISTS professionals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    bio TEXT,
    automatic_approval BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS services (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professional_id INTEGER NOT NULL REFERENCES professionals(id),
    name VARCHAR(100) NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    price INTEGER NOT NULL CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS bookings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id INTEGER NOT NULL REFERENCES services(id),
    customer_name VARCHAR(100) NOT NULL,
    customer_phone VARCHAR(30) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending',
            'confirmed',
            'rejected',
            'cancelled',
            'completed'
        )),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (ends_at > starts_at)
);

-- Minutos de la jornada civil del profesional en America/Santiago.
-- Domingo=0; varios intervalos permiten representar el descanso de mediodía.
CREATE TABLE IF NOT EXISTS working_hours (
    professional_id INTEGER NOT NULL REFERENCES professionals(id),
    weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    start_minute INTEGER NOT NULL CHECK (start_minute >= 0),
    end_minute INTEGER NOT NULL CHECK (end_minute <= 1440),
    CHECK (start_minute < end_minute),
    PRIMARY KEY (professional_id, weekday, start_minute)
);

-- Columnas opcionales: los profesionales existentes se conservan sin contraseña predeterminada.
ALTER TABLE professionals ADD COLUMN IF NOT EXISTS email TEXT;
ALTER TABLE professionals ADD COLUMN IF NOT EXISTS password_hash TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS professionals_email_unique ON professionals(lower(email)) WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS professional_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    professional_id INTEGER NOT NULL REFERENCES professionals(id),
    csrf_token CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS professional_sessions_expiry ON professional_sessions(expires_at);
CREATE INDEX IF NOT EXISTS bookings_pending_fifo ON bookings(created_at,id) WHERE status='pending';

