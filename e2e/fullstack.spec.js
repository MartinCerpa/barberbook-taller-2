test('móvil conserva navegación, no desborda y comunica error de API',async ({ page }) => {
  await page.setViewportSize({ width: 390,height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByLabel('Profesional',{ exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/evidence/profile-mobile.png',fullPage: true })
  await page.goto('/#/panel/queue')
  await expect(page.getByRole('button',{ name: 'Emitir turno',exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/evidence/queue-mobile.png',fullPage: true })
  await page.route('**/api/services',(route) => route.abort())
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('No pudimos conectar con la API')
  await page.getByRole('button',{ name: 'Reintentar conexión' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
})

test('administración React persiste sucursal, profesional, módulo, servicio y jornada',async ({ page,request }) => {
  await page.goto('/#/panel/settings')
  const card=(name) => page.locator('section.fs-card').filter({ has: page.getByRole('heading',{ name,exact: true }) })
  const branches=card('Sucursales')
  await branches.getByLabel('Nombre',{ exact: true }).fill('Sucursal E2E')
  await branches.getByLabel('Dirección ficticia').fill('Dirección de prueba sin ubicación real')
  await branches.getByRole('button',{ name: 'Crear registro',exact: true }).click()
  await expect(branches.getByText('Sucursal E2E',{ exact: true })).toBeVisible()
  const branch=(await (await request.get('/api/branches')).json()).data.find((b) => b.name==='Sucursal E2E')
  const people=card('Profesionales')
  await people.getByLabel('Nombre ficticio').fill('Profesional E2E')
  await people.getByRole('combobox',{ name: 'Sucursal',exact: true }).selectOption(branch.id)
  await people.getByLabel('Especialidad').fill('Barba ficticia')
  await people.getByRole('button',{ name: 'Crear registro',exact: true }).click()
  await expect(people.getByText('Profesional E2E',{ exact: true })).toBeVisible()
  const person=(await (await request.get('/api/professionals')).json()).data.find((p) => p.name==='Profesional E2E')
  const modules=card('Módulos de atención')
  await modules.getByLabel('Nombre',{ exact: true }).fill('Sillón E2E')
  await modules.getByRole('combobox',{ name: 'Sucursal',exact: true }).selectOption(branch.id)
  await modules.getByRole('combobox',{ name: 'Profesional',exact: true }).selectOption(person.id)
  await modules.getByRole('button',{ name: 'Crear registro',exact: true }).click()
  await expect(modules.getByText('Sillón E2E',{ exact: true })).toBeVisible()
  const weekly=card('Horario semanal')
  const loaded=page.waitForResponse((response) => response.url().includes(`/availability/weekly?professionalId=${person.id}`))
  await weekly.getByLabel('Profesional del horario').selectOption(person.id)
  await loaded
  await weekly.getByRole('button',{ name: 'Agregar intervalo',exact: true }).click()
  await weekly.getByRole('button',{ name: 'Guardar horario',exact: true }).click()
  await expect(page.getByText('Horario guardado.',{ exact: true })).toBeVisible()
  const intervals=(await (await request.get(`/api/availability/weekly?professionalId=${person.id}`)).json()).data
  expect(intervals.some((i) => i.weekday===1 && i.startMinute===600 && i.endMinute===780)).toBe(true)
  await page.goto('/#/panel/services')
  const services=card('Servicios')
  await services.getByLabel('Nombre',{ exact: true }).fill('Servicio E2E')
  await services.getByRole('combobox',{ name: 'Sucursal',exact: true }).selectOption(branch.id)
  await services.getByLabel('Duración (min)').fill('30')
  await services.getByLabel('Precio (CLP)').fill('5000')
  await services.getByRole('button',{ name: 'Crear registro',exact: true }).click()
  await expect(services.getByText('Servicio E2E',{ exact: true })).toBeVisible()
  await page.reload()
  await expect(services.getByText('Servicio E2E',{ exact: true })).toBeVisible()
})
