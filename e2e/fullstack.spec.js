import { test,expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test('reserva React → SQL → confirmación → agenda → MongoDB',async ({ page,request }) => {
  const errors=[]
  page.on('pageerror',(error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByLabel('Profesional',{ exact: true })).toBeVisible()
  await page.getByRole('button',{ name: /^Reservar ahora/ }).first().click()
  await page.locator('label:has(input[name="booking-service"][value="haircut"])').click()
  await expect(page.getByRole('heading',{ name: 'Elige una fecha' })).toBeVisible()
  const dates=page.locator('input[name="booking-date"]:not([disabled])')
  // Evita el día actual: el flujo de agenda debe ser estable aunque cambie la hora.
  const dateId=await dates.nth(1).inputValue()
  await dates.nth(1).locator('..').click()
  await expect(page.getByRole('heading',{ name: 'Selecciona una hora' })).toBeVisible()
  await page.locator('input[name="booking-time"]:not([disabled])').first().locator('..').click()
  await page.getByLabel(/Nombre/).fill('Cliente Navegador')
  await page.getByLabel(/Teléfono/).fill('+56900000002')
  await page.getByRole('button',{ name: 'Revisar solicitud',exact: true }).click()
  await page.getByRole('button',{ name: /Enviar solicitud/ }).click()
  await expect(page.getByRole('heading',{ name: 'Tu solicitud fue enviada' })).toBeVisible()
  await page.reload()
  const stored=(await (await request.get('/api/bookings')).json()).data.find((b) => b.customerName==='Cliente Navegador')
  expect(stored.status).toBe('pending')
  await page.goto('/#/panel/requests')
  await page.getByRole('button',{ name: 'Confirmar solicitud de Cliente Navegador',exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Estado de la reserva actualizado.' })).toBeVisible()
  await page.goto('/#/panel/schedule')
  await page.getByLabel('Filtrar fecha',{ exact: true }).fill(dateId)
  await expect(page.getByRole('heading',{ name: 'Cliente Navegador',exact: true })).toBeVisible()
  await page.goto('/#/panel/history')
  await expect(page.getByText('booking.confirmed',{ exact: true })).toBeVisible()
  await expect(page.getByText('booking.created',{ exact: true })).toBeVisible()
  await mkdir('test-results/evidence',{ recursive: true })
  await page.screenshot({ path: 'test-results/evidence/history-desktop.png',fullPage: true })
  expect(errors).toEqual([])
})

